import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire('C:/Users/Lakshya Arora/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.js');
const { chromium } = require('playwright');
const out = path.resolve('output/pitch-build/screenshots');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:8012/', { waitUntil: 'networkidle' });
await page.locator('#api-key').fill(process.env.PITCH_DEMO_KEY);
await page.locator('#auth-form button[type="submit"]').click();
await page.locator('#system-status-text').waitFor();
await page.waitForTimeout(1100);
await page.screenshot({ path: path.join(out, '01-intake.png') });
await page.locator('.nav-item[data-view="review"]').click();
await page.locator('.case-open').first().waitFor();
await page.screenshot({ path: path.join(out, '02-review-queue.png') });
await page.locator('.case-open').first().click();
await page.locator('#case-summary .balance-story').waitFor();
await page.locator('#case-summary').screenshot({ path: path.join(out, '03-balance-evidence.png') });
await page.locator('#case-history').screenshot({ path: path.join(out, '04-source-evidence.png') });
await page.locator('#negotiation-panel').screenshot({ path: path.join(out, '05-negotiation.png') });
await page.locator('.nav-item[data-view="control"]').click();
await page.waitForTimeout(800);
await page.screenshot({ path: path.join(out, '06-control.png') });
console.log(JSON.stringify({ title: await page.title(), url: page.url(), errors, screenshots: await fs.readdir(out) }));
await browser.close();
